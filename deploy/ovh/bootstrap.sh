#!/bin/bash
# One-time (idempotent) preparation of the VPS for Keygate: packages, service account, PostgreSQL (local only),
# secrets file, systemd units, encrypted backups, Caddy (installed but NOT started), small hardening.
# It does NOT open ports 80/443, does NOT touch SSH, DNS or the existing mail setup.
#   sudo ./bootstrap.sh            (run from the copied deploy directory)
set -euo pipefail
[ "$(id -u)" -eq 0 ] || { echo "run with sudo" >&2; exit 1; }
SRC=$(cd "$(dirname "$0")" && pwd)
DOMAIN=${KEYGATE_DOMAIN:-api.alc-control.com}
ADMIN_EMAIL=${ADMIN_EMAIL:-contact@alc-control.com}
say() { printf '\n== %s\n' "$*"; }

say "Packages"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq postgresql caddy curl openssl ca-certificates dnsutils fail2ban unattended-upgrades >/dev/null
# Caddy only starts later, once the DNS record exists (enable-https.sh).
systemctl disable --now caddy >/dev/null 2>&1 || true

say "Service account and directories"
id keygate >/dev/null 2>&1 || adduser --system --group --no-create-home --home /nonexistent --shell /usr/sbin/nologin keygate
install -d -m 0755 -o root -g root /opt/keygate /opt/keygate/releases /opt/keygate/deploy
install -d -m 0750 -o root -g root /etc/keygate
install -d -m 0700 -o root -g root /var/backups/keygate /var/lib/keygate-backup

say "Deploy tooling -> /opt/keygate/deploy"
for f in README.md Caddyfile keygate.env.example *.sh *.service *.timer; do
  [ -e "$SRC/$f" ] && install -m 0755 -o root -g root "$SRC/$f" /opt/keygate/deploy/ || true
done
for s in backup restore install-release enable-https set-secret smtp-check smtp-test-send; do
  ln -sfn "/opt/keygate/deploy/$s.sh" "/usr/local/sbin/keygate-$s"
done

say "PostgreSQL (local only) and secrets file"
systemctl enable --now postgresql >/dev/null
for _ in $(seq 1 20); do runuser -u postgres -- psql -X -q -At -c 'select 1' >/dev/null 2>&1 && break; sleep 1; done
ENVF=/etc/keygate/keygate.env
if [ ! -e "$ENVF" ]; then
  umask 077
  DBPW=$(openssl rand -hex 24)
  JWT=$(openssl rand -hex 32); SIGN=$(openssl rand -hex 32); ENC=$(openssl rand -hex 32)
  cat > "$ENVF" <<ENVEOF
# Generated by bootstrap.sh on $(date -u +%FT%TZ). root:root 0600. Never commit, never paste.
PORT=9000
ENVIRONMENT=production
BASE_URL=https://$DOMAIN
DATABASE_URL=postgres://keygate:$DBPW@127.0.0.1:5432/keygate?sslmode=disable
JWT_SECRET=$JWT
LICENSE_SIGNING_KEY=$SIGN
RELEASE_KEY_ENCRYPTION_KEY=$ENC
ADMIN_EMAILS=$ADMIN_EMAIL
TRUSTED_PROXIES=127.0.0.1/32,::1/128
ALC_KEY_PRODUCT_IDS=
SMTP_HOST=smtp.mail.ovh.net
SMTP_PORT=587
SMTP_USERNAME=contact@alc-control.com
SMTP_FROM="Autotune Live Control <contact@alc-control.com>"
SMTP_PASSWORD=
ENVEOF
  chmod 600 "$ENVF"; chown root:root "$ENVF"
  runuser -u postgres -- psql -X -q -v ON_ERROR_STOP=1 <<SQLEOF
DO \$\$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'keygate') THEN CREATE ROLE keygate LOGIN; END IF;
END \$\$;
ALTER ROLE keygate WITH LOGIN PASSWORD '$DBPW';
SQLEOF
  unset DBPW JWT SIGN ENC
  echo "secrets file created: $ENVF (values not displayed)"
else
  echo "secrets file already present: left untouched"
fi
runuser -u postgres -- psql -X -q -At -c "SELECT 1 FROM pg_database WHERE datname='keygate'" | grep -q 1 \
  || runuser -u postgres -- createdb -O keygate keygate
echo "PostgreSQL listening sockets:"; ss -ltn | awk 'NR==1 || /:5432/'

say "Encrypted backups"
if [ ! -e /etc/keygate/backup.pass ]; then
  ( umask 077; openssl rand -base64 32 > /etc/keygate/backup.pass ); chmod 400 /etc/keygate/backup.pass
  echo "backup passphrase file created: /etc/keygate/backup.pass (copy it OFF this server, see README)"
fi

say "systemd units"
for u in keygate.service keygate-backup.service keygate-backup.timer keygate-health.service keygate-health.timer; do
  install -m 0644 -o root -g root "$SRC/$u" /etc/systemd/system/
done
systemctl daemon-reload
systemctl enable keygate.service keygate-backup.timer >/dev/null
systemctl start keygate-backup.timer

say "Caddy configuration (not started)"
[ -e /etc/caddy/Caddyfile.orig ] || cp /etc/caddy/Caddyfile /etc/caddy/Caddyfile.orig 2>/dev/null || true
sed "s/api\.alc-control\.com/$DOMAIN/g" "$SRC/Caddyfile" > /etc/caddy/Caddyfile
caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null 2>&1 && echo "Caddyfile valid" || echo "WARNING: Caddyfile did not validate"

say "Hardening"
printf 'APT::Periodic::Update-Package-Lists "1";\nAPT::Periodic::Unattended-Upgrade "1";\n' > /etc/apt/apt.conf.d/20auto-upgrades
systemctl enable --now fail2ban >/dev/null 2>&1 || true
# Port 5355 is LLMNR (systemd-resolved): not needed on a server, switched off only if name resolution keeps working.
if ss -lntu | grep -q ':5355'; then
  echo "port 5355 is open (LLMNR); disabling LLMNR"
  mkdir -p /etc/systemd/resolved.conf.d
  printf '[Resolve]\nLLMNR=no\nMulticastDNS=no\n' > /etc/systemd/resolved.conf.d/no-llmnr.conf
  systemctl restart systemd-resolved
  sleep 2
  if ! getent hosts deb.debian.org >/dev/null; then
    echo "name resolution broke: reverting"; rm -f /etc/systemd/resolved.conf.d/no-llmnr.conf; systemctl restart systemd-resolved
  fi
fi

say "State"
ufw status | head -12 || true
echo "listening sockets:"; ss -ltnup | awk 'NR==1 || /LISTEN|UNCONN/' | cut -c1-110
echo
echo "Next: install a release (install-release.sh), set the SMTP password (keygate-set-secret SMTP_PASSWORD), create the DNS record, run keygate-enable-https."
